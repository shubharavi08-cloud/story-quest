#!/usr/bin/env python3
"""AI-discoverability (GEO) builder for Shubha's static GitHub Pages sites.

Usage:
    python3 geo_build.py quad /path/to/quad-site
    python3 geo_build.py wow  /path/to/story-quest

What it does (idempotent: safe to re-run after any site edit):
  * writes robots.txt (all crawlers + named AI crawlers allowed, sitemap link)
  * writes sitemap.xml (every page, lastmod from git history)
  * writes llms.txt (plain-language summary AI assistants can read)
  * injects JSON-LD structured data + canonical link into each page <head>
    between <!-- geo:start --> / <!-- geo:end --> markers (replaced on re-run)
  * adds a meta description where a page has none
  * (wow) writes about.html, a crawlable About + FAQ page
Facts live in geo_sites.py; edit there when dates, prices or pages change.
"""
import json, re, subprocess, sys, pathlib, html
from geo_sites import SITES

AI_BOTS = ["GPTBot", "OAI-SearchBot", "ChatGPT-User", "ClaudeBot", "Claude-User",
           "Claude-SearchBot", "PerplexityBot", "Perplexity-User", "Google-Extended",
           "Applebot-Extended", "Bingbot", "Googlebot"]


def robots(base):
    lines = ["# Every crawler, including AI assistants, may read this site.", "User-agent: *", "Allow: /", ""]
    for b in AI_BOTS:
        lines += [f"User-agent: {b}", "Allow: /", ""]
    lines.append(f"Sitemap: {base}sitemap.xml")
    return "\n".join(lines) + "\n"


def lastmod(repo, rel):
    try:
        out = subprocess.run(["git", "-C", str(repo), "log", "-1", "--format=%cs", "--", rel],
                             capture_output=True, text=True).stdout.strip()
        return out or None
    except Exception:
        return None


def sitemap(repo, base, pages):
    rows = []
    for p in pages:
        loc = base + ("" if p["path"] == "index.html" else p["path"].replace("index.html", ""))
        lm = lastmod(repo, p["path"])
        rows.append(f"  <url><loc>{html.escape(loc)}</loc>" + (f"<lastmod>{lm}</lastmod>" if lm else "")
                    + f"<priority>{p.get('priority', 0.6)}</priority></url>")
    return ('<?xml version="1.0" encoding="UTF-8"?>\n'
            '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n' + "\n".join(rows) + "\n</urlset>\n")


def page_url(base, path):
    return base + ("" if path == "index.html" else path.replace("index.html", ""))


def head_block(base, page):
    parts = [f'<link rel="canonical" href="{page_url(base, page["path"])}">']
    for obj in page.get("jsonld", []):
        obj = {"@context": "https://schema.org", **obj}
        parts.append('<script type="application/ld+json">' +
                     json.dumps(obj, ensure_ascii=False, separators=(",", ":")).replace("</", "<\\/") +
                     "</script>")
    return "<!-- geo:start (generated by geo_build.py; edit geo_sites.py, not here) -->\n" + \
           "\n".join(parts) + "\n<!-- geo:end -->\n"


def patch_page(file, base, page):
    s = file.read_text(encoding="utf-8")
    orig = s
    s = re.sub(r"<!-- geo:start.*?<!-- geo:end -->\n?", "", s, flags=re.S)
    if page.get("faq_from_details"):
        # FAQ schema built from the page's own visible <details> Q&A, so it never drifts from the page
        qa = re.findall(r"<details><summary>(.*?)</summary><p>(.*?)</p></details>", s, flags=re.S)
        clean = lambda t: html.unescape(re.sub(r"<[^>]+>", "", t)).strip()
        page = {**page, "jsonld": page.get("jsonld", []) + [{"@type": "FAQPage", "mainEntity": [
            {"@type": "Question", "name": clean(q), "acceptedAnswer": {"@type": "Answer", "text": clean(a)}}
            for q, a in qa]}]}
    if page.get("title"):
        s = re.sub(r"<title>.*?</title>", f"<title>{html.escape(page['title'])}</title>", s, count=1, flags=re.S)
    if page.get("description") and not re.search(r'<meta\s+name="description"', s):
        s = s.replace("</title>", "</title>\n<meta name=\"description\" content=\"" +
                      html.escape(page["description"], quote=True) + "\">", 1)
    if s.count("</head>") != 1:
        sys.exit(f"{file}: expected exactly one </head>")
    s = s.replace("</head>", head_block(base, page) + "</head>", 1)
    for old, new in page.get("replace", []):
        if new in s:
            continue
        if s.count(old) != 1:
            sys.exit(f"{file}: anchor not found exactly once: {old[:60]}")
        s = s.replace(old, new, 1)
    if s != orig:
        file.write_text(s, encoding="utf-8")
        return True
    return False


def main():
    if len(sys.argv) != 3 or sys.argv[1] not in SITES:
        sys.exit(__doc__)
    site = SITES[sys.argv[1]]
    repo = pathlib.Path(sys.argv[2]).resolve()
    base = site["base"]
    for name, content in site.get("extra_files", {}).items():
        (repo / name).write_text(content, encoding="utf-8")
        print("wrote", name)
    changed = []
    for page in site["pages"]:
        f = repo / page["path"]
        if not f.exists():
            sys.exit(f"missing page {f}")
        if patch_page(f, base, page):
            changed.append(page["path"])
    (repo / "robots.txt").write_text(robots(base), encoding="utf-8")
    (repo / "sitemap.xml").write_text(sitemap(repo, base, site["pages"]), encoding="utf-8")
    (repo / "llms.txt").write_text(site["llms"], encoding="utf-8")
    print("wrote robots.txt, sitemap.xml, llms.txt")
    print("patched:", ", ".join(changed) or "nothing (already up to date)")


if __name__ == "__main__":
    main()
