#!/usr/bin/env python3
"""Build jagruth-bharath/cases/cases.js for Mauna's Case Book.

Inputs (same folder as this script by default):
  episodes_src.json      ids per language (en/hi/kn), sched (ISO, optional), facts
  episodes_content.json  trilingual title/bait/steps/rules/quiz/lesson/help/icon/color
  blog_links.json        optional {"ep:14": "https://jagruthbharath.blogspot.com/...", "weekly:1": "..."}

Usage: python3 _tools/jb_cases/build_cases.py [src.json content.json [blog_links.json]]
Adding a new episode = add it to both JSON files, run this, commit cases.js.
"""
import json, os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
src_p = sys.argv[1] if len(sys.argv) > 1 else os.path.join(HERE, "episodes_src.json")
con_p = sys.argv[2] if len(sys.argv) > 2 else os.path.join(HERE, "episodes_content.json")
blog_p = sys.argv[3] if len(sys.argv) > 3 else os.path.join(HERE, "blog_links.json")
OUT = os.path.join(ROOT, "jagruth-bharath", "cases", "cases.js")

src = json.load(open(src_p, encoding="utf-8"))
con = json.load(open(con_p, encoding="utf-8"))
blog = json.load(open(blog_p, encoding="utf-8")) if os.path.exists(blog_p) else {}
LANGS = ("en", "hi", "kn")


def merge(s, c, key):
    assert s["n"] == c["n"], (s["n"], c["n"])
    o = {k: c[k] for k in ("n", "slug", "icon", "color", "t", "bait", "steps", "rules", "quiz", "lesson", "help") if k in c}
    o["yt"] = {l: s[l] for l in LANGS if s.get(l)}
    if s.get("sched"):
        o["sched"] = s["sched"]
    if blog.get(f"{key}:{s['n']}"):
        o["blog"] = blog[f"{key}:{s['n']}"]
    return o


def check(o, label):
    for f in ("t", "lesson"):
        for l in LANGS:
            assert o[f].get(l), f"{label} missing {f}.{l}"
    for q in o.get("quiz", []):
        for l in LANGS:
            assert len(q["o"][l]) == 3 and q["q"][l] and q["why"][l], f"{label} quiz {l}"
        assert 0 <= q["a"] <= 2, label
    assert set(o["yt"]) == set(LANGS), f"{label} missing a language video"


cmap = {c["n"]: c for c in con["eps"]}
eps = []
for s in src["eps"]:
    if s["n"] not in cmap:
        print("skip (no content yet): ep", s["n"]); continue
    o = merge(s, cmap[s["n"]], "ep"); check(o, f"ep{s['n']}"); eps.append(o)
wmap = {c["n"]: c for c in con.get("weekly", [])}
weekly = []
for s in src.get("weekly", []):
    if s["n"] in wmap:
        o = merge(s, wmap[s["n"]], "weekly"); check(o, f"weekly{s['n']}"); weekly.append(o)

js = ("/* generated by _tools/jb_cases/build_cases.py: do not edit by hand */\n"
      "window.JB_EPS=" + json.dumps(eps, ensure_ascii=False, separators=(",", ":")) + ";\n"
      "window.JB_WEEKLY=" + json.dumps(weekly, ensure_ascii=False, separators=(",", ":")) + ";\n")
os.makedirs(os.path.dirname(OUT), exist_ok=True)
open(OUT, "w", encoding="utf-8").write(js)
print(f"wrote {OUT}: {len(eps)} episodes, {len(weekly)} weekly, {len(js)//1024} KB")
